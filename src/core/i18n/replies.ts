function normalizeReplyConfig(config: Partial<ReplyConfig> | undefined): ReplyConfig {
  const customPresets = { ...(config?.customPresets || {}) }
  let activePreset = config?.activePreset || config?.preset || DEFAULT_REPLY_CONFIG.activePreset

  if (config?.overrides && Object.keys(config.overrides).length) {
    const base = config.preset && REPLY_TEMPLATES[config.preset] ? config.preset : DEFAULT_REPLY_CONFIG.activePreset as BuiltinReplyPreset
    const legacyId = `custom-${base}`
    if (!customPresets[legacyId]) {
      customPresets[legacyId] = {
        id: legacyId,
        label: `${REPLY_PRESETS.find(item => item.id === base)?.label || base} 自定义`,
        base,
        overrides: { ...config.overrides }
      }
    }
    activePreset = legacyId
  }

  return {
    locale: config?.locale || DEFAULT_REPLY_CONFIG.locale,
    activePreset,
    customPresets
  }
}

function getActivePreset(config: Partial<ReplyConfig> | undefined): { base: BuiltinReplyPreset; overrides: Record<string, string> } {
  const normalized = normalizeReplyConfig(config)
  const custom = normalized.customPresets[normalized.activePreset]
  if (custom) {
    const base = REPLY_TEMPLATES[custom.base] ? custom.base : DEFAULT_REPLY_CONFIG.activePreset as BuiltinReplyPreset
    return { base, overrides: custom.overrides || {} }
  }

  const base = REPLY_TEMPLATES[normalized.activePreset as BuiltinReplyPreset]
    ? normalized.activePreset as BuiltinReplyPreset
    : DEFAULT_REPLY_CONFIG.activePreset as BuiltinReplyPreset
  return { base, overrides: {} }
}

export function resolveReplyTemplate(config: Partial<ReplyConfig> | undefined, key: string): string {
  const preset = getActivePreset(config)
  return preset.overrides[key]
    ?? REPLY_TEMPLATES[preset.base][key]
    ?? REPLY_TEMPLATES[DEFAULT_REPLY_CONFIG.activePreset as BuiltinReplyPreset][key]
    ?? key
}

export function renderReplyTemplate(template: string, variables: Record<string, unknown> = {}): string {
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) => {
    const value = variables[name]
    return value === undefined || value === null ? match : String(value)
  })
}

export function renderReply(config: Partial<ReplyConfig> | undefined, key: string, variables?: Record<string, unknown>): string {
  return renderReplyTemplate(resolveReplyTemplate(config, key), variables)
}

export function getReplyCatalog() {
  return {
    presets: REPLY_PRESETS,
    templates: REPLY_TEMPLATE_META,
    defaults: REPLY_TEMPLATES
  }
}
